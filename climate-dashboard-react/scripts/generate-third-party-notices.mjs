// Generates THIRD-PARTY-NOTICES.md at the repository root: the licence notices for what ships in the front-end build.
//
// Scope: the production npm packages of this app, the production npm packages of the design system it compiles
// (its source is built into the app's bundle), and the two font packages the design system's tokens point at.
// Development tooling is not in the build and is not listed.
//
// Run from climate-dashboard-react/ with the design system set up (see ../README.md); SYN_DS_PATH overrides its location:
//   node scripts/generate-third-party-notices.mjs
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const appDir = path.resolve(here, '..');
const dsDir = path.resolve(appDir, process.env.SYN_DS_PATH ?? '../../syena-design-system');
const outFile = path.resolve(appDir, '../THIRD-PARTY-NOTICES.md');
const FONTS = ['@fontsource/poppins', '@fontsource-variable/inter'];

// Production closure of a folder's package.json. `npm ls` marks leftovers in node_modules that nothing requires as
// EXTRANEOUS; those and the @types packages (type declarations, not code) are not in the build.
const prodPaths = (dir) =>
  execFileSync('npm', ['ls', '--omit=dev', '--all', '--parseable', '--long'], { cwd: dir, encoding: 'utf8', maxBuffer: 1e8 })
    .split('\n')
    .filter((line) => line && !line.includes(':EXTRANEOUS'))
    .map((line) => line.split(':')[0])
    .filter((p) => p !== dir && !p.includes(`${path.sep}@types${path.sep}`) && fs.existsSync(path.join(p, 'package.json')));

const found = new Map(); // "name@version" -> { dir, from }
const add = (dir, from) => {
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const key = `${pkg.name}@${pkg.version}`;
  if (!found.has(key)) found.set(key, { dir, from, pkg });
};
for (const p of prodPaths(appDir)) add(p, 'this app');
for (const p of prodPaths(dsDir)) add(p, 'design system');
for (const f of FONTS) add(path.join(dsDir, 'node_modules', f), 'design system (font)');

// Contact e-mail addresses are left out of the copyright lines (the names and years stay); the rest of each text is verbatim.
const redact = (text) =>
  text.replace(/[ \t]*[<(][^<>()\s]+@[^<>()\s]+[>)]/g, '').replace(/[ \t]*\b[\w.+-]+@[\w-]+(?:\.[\w-]+)+/g, '');

const licenceFile = (dir) => {
  const names = fs.readdirSync(dir).filter((n) => /^(licen[cs]e|copying)([-._].*)?$/i.test(n) && fs.statSync(path.join(dir, n)).isFile());
  names.sort((a, b) => (/\.(md|txt)$|^[^.]*$/i.test(a) ? 0 : 1) - (/\.(md|txt)$|^[^.]*$/i.test(b) ? 0 : 1));
  return names.length ? redact(fs.readFileSync(path.join(dir, names[0]), 'utf8').replace(/\r\n/g, '\n').trim()) : null;
};
const spdx = (pkg) => (typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR ')) || 'UNKNOWN';
const repo = (pkg) => {
  const r = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '';
  return r.replace(/^git\+/, '').replace(/^git:\/\//, 'https://').replace(/\.git$/, '').replace(/^github:/, 'https://github.com/');
};

const entries = [...found.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([key, v]) => ({ key, ...v, licence: spdx(v.pkg), text: licenceFile(v.dir), repo: repo(v.pkg) }));

const groups = new Map(); // text hash -> { text, items }
const withoutText = [];
for (const e of entries) {
  if (!e.text) { withoutText.push(e); continue; }
  const h = createHash('sha256').update(e.text.replace(/^.*copyright.*$/gim, '').replace(/\s+/g, ' ')).digest('hex');
  if (!groups.has(h)) groups.set(h, { text: e.text, items: [] });
  groups.get(h).items.push(e);
}

let md = `# Third-party notices

This file lists the third-party software that ships in the front-end build of this platform, with each package's licence. It covers the production npm packages of \`climate-dashboard-react\`, the production npm packages of the design system the app compiles (\`@syena/ds\`), and the two typefaces the design system loads. Development tools are not in the build and are not listed. The notice in [LICENSE](LICENSE) covers this repository's own code only; the packages below keep their own licences.

Generated by \`climate-dashboard-react/scripts/generate-third-party-notices.mjs\`. Regenerate it after dependencies change.

- Packages: ${entries.length}
- Typefaces: Poppins (interface) and Inter (figures), both under the SIL Open Font License 1.1, shipped as the \`@fontsource\` packages.
- Country shapes come from \`world-atlas\` (ISC), which derives from Natural Earth, a public-domain dataset.
- \`plotly.js\` bundles its own dependencies inside its distribution files; see the plotly.js licence below and its upstream repository for those.

## Packages

| Package | Version | Licence | Included through | Source |
|---|---|---|---|---|
`;
for (const e of entries) md += `| ${e.pkg.name} | ${e.pkg.version} | ${e.licence} | ${e.from} | ${e.repo || ''} |\n`;

md += `\n## Licence texts\n\nPackages whose licence text is identical (apart from the copyright line) share one entry. Each package's own copyright line is shown with it.\n`;
const copyrightLines = (text) => text.split('\n').filter((l) => /^\s*(copyright\b|\(c\)|©)/i.test(l)).map((l) => l.trim().slice(0, 200)).filter(Boolean).slice(0, 3);
let n = 0;
for (const g of [...groups.values()].sort((a, b) => b.items.length - a.items.length)) {
  n += 1;
  const ids = [...new Set(g.items.map((i) => i.licence))].join(', ');
  md += `\n### ${n}. ${ids}\n\nUsed by: ${g.items.map((i) => `${i.pkg.name}@${i.pkg.version}`).join(', ')}\n\n`;
  const seen = new Set();
  for (const i of g.items) for (const l of copyrightLines(i.text)) if (!seen.has(l)) { seen.add(l); md += `- ${i.pkg.name}: ${l}\n`; }
  md += `\n\`\`\`text\n${g.items[0].text}\n\`\`\`\n`;
}
if (withoutText.length) {
  md += `\n## Packages that ship no licence file\n\nThese packages declare their licence in package.json but include no licence text; the standard text of the declared licence applies.\n\n`;
  for (const e of withoutText) md += `- ${e.pkg.name}@${e.pkg.version}: ${e.licence}${e.repo ? ` (${e.repo})` : ''}\n`;
}
fs.writeFileSync(outFile, md.replace(/[ \t]+$/gm, '') );
console.log(`wrote ${path.relative(process.cwd(), outFile)}: ${entries.length} packages, ${groups.size} distinct licence texts, ${withoutText.length} without a licence file`);
